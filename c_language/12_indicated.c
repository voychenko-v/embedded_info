#include <stdio.h>

/*
Вказівник - це змінна, яка зберігає адресу іншого об'єкта в пам'яті.
Наприклад, int *p зберігає адресу змінної типу int.

Для чого потрібні вказівники:
- змінювати значення змінної через її адресу;
- передавати у функції великі об'єкти без копіювання;
- працювати з масивами, рядками та динамічною пам'яттю;
- будувати складні структури даних: списки, дерева, черги тощо.

Основні оператори:
& - оператор взяття адреси. Повертає адресу змінної.
* - оператор розіменування. Дозволяє отримати або змінити значення за адресою.

Важливо:
- не можна розіменовувати неініціалізований вказівник;
- не можна розіменовувати NULL-вказівник;
- тип вказівника має відповідати типу змінної, на яку він вказує;
- для printf з форматом %p адресу потрібно передавати як (void *). У стандарті C для %p сказано: аргумент має бути типу void *
Якщо передати вказівник іншого типу (наприклад, int * або char *), програма може працювати на одній архітектурі, але зламатися на іншій.

Приклад виводу адреси памяті:
0000002E9F7FF700 — це адреса пам’яті, записана у шістнадцятковій системі числення на 64-бітній системі, адреси зазвичай мають розмір 8 байт, тобто 64 біти.
*/

int main(void)
{
    int var = 100; // Ініціалізація змінної
    int *ind; // Оголошення вказівника, який може зберігати адресу змінної типу int

    ind = &var; // &var - адреса змінної var

    printf("Variable value: %d\n", var);
    printf("Variable address: %p\n", (void *)&var);
    printf("Pointer value: %p\n", (void *)ind);

    int var_2 = *ind; // *ind - значення змінної, на яку вказує ind
    printf("Variable value through pointer: %d\n", var_2);

    *ind = 200; // Змінюємо var через вказівник ind
    printf("Variable value after changing through pointer: %d\n", var);
    printf("var_2 value: %d\n", var_2); // var_2 - окрема змінна, тому вона не змінилася

    int int_arg = 9;
    int *a;
    int *b;

    a = &int_arg;
    b = a; // a і b зберігають одну й ту саму адресу

    printf("Pointer a value: %p\n", (void *)a);
    printf("Pointer b value: %p\n", (void *)b);
    printf("int_arg value through a: %d\n", *a);

    *b = 15; // Змінюємо int_arg через b
    printf("int_arg value after changing through b: %d\n", int_arg);
    printf("int_arg value through a: %d\n", *a);

    int *int_ind = &int_arg;
    short short_arg = 5;
    short *short_ind = &short_arg;

    printf("int value through int_ind: %d\n", *int_ind);
    printf("short value through short_ind: %hd\n", *short_ind);

    /*
    short_ind = &int_arg; робити НЕ МОЖНА.

    short_ind має тип short *, тому він повинен зберігати адресу змінної типу short.
    int_arg має тип int, тому його адресу потрібно зберігати у вказівнику типу int *.

    Тип вказівника підказує компілятору, як інтерпретувати пам'ять під час
    розіменування. Наприклад, short зазвичай займає 2 байти, а int зазвичай
    займає 4 байти.

    short_ind = (short *)int_ind; технічно можна написати через явне приведення типів,
    але для такого навчального прикладу це погана ідея: ми змусимо компілятор
    дивитися на int як на short. Так можна отримати неправильні дані або
    важку для пошуку помилку.
    */

    void *p;

    /*
    void *p - це вказівник на "невідомий тип".

    Він може зберігати адресу змінної будь-якого типу:
    p = &int_arg;   // можна
    p = &short_arg; // можна

    Але через void * не можна напряму отримати значення:
    printf("%d\n", *p); // не можна

    Компілятор не знає, який тип лежить за адресою, тому перед розіменуванням
    void * потрібно привести до правильного типу:
    printf("%d\n", *(int *)p);

    Найчастіші випадки використання void *:
    1. Динамічна пам'ять.
       malloc повертає void *, бо вона просто виділяє шматок пам'яті, не знаючи, що саме ти там будеш зберігати.

    2. Універсальні функції.
       Функція може приймати адресу будь-якого значення через параметр void *.

    3. Універсальні контейнери.
       Наприклад, список, стек або черга можуть зберігати void *, а користувач контейнера сам знає, який тип там лежить.
    */

    p = &int_arg;
    printf("Void int: %d\n", *(int *)p);

    p = &short_arg;
    printf("Void short: %hd\n", *(short *)p);

    /*
    NULL - це спеціальне значення вказівника, яке означає:
    "цей вказівник зараз не вказує на жодний об'єкт".

    Це корисно для безпечної початкової ініціалізації.
    Перед розіменуванням такого вказівника потрібно перевірити, що він не NULL.
    */

    int *asc = NULL;

    if (asc != NULL)
        *asc = 10;

    asc = &int_arg;

    if (asc != NULL)
        *asc = 10;

    printf("int_arg value after changing through asc: %d\n", int_arg);

    return 0;
}
