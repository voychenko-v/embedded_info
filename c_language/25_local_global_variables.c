#include <stdio.h>

/*
    Локальні та глобальні змінні в C

    1. Глобальні змінні:
       - Оголошуються поза всіма функціями.
       - Мають глобальну область видимості: доступні з усіх функцій у тому самому файлі
         (або з інших файлів за допомогою extern).
       - Ініціалізуються за замовчуванням нулем, якщо не мають явного значення.
       - Живуть протягом усього часу виконання програми.

    2. Локальні змінні:
       - Оголошуються всередині функцій або блоків ({ ... }).
       - Мають область видимості лише в тій функції/блоці, де оголошені.
       - Ініціалізуються лише якщо явно задано значення; інакше містять невизначені дані.
       - Живуть тільки під час виконання функції/блоку.

    2.1. Ключове слово register:
       - Використовується для підказки компілятору зберігати змінну в регістрі CPU,
         а не у пам'яті.
       - Синтаксис: "register int x;".
       - Змінна з register має локальну область видимості і автоматичну тривалість життя.
       - Вас не буде доступний синтаксичним чином через & (адреса) для деяких компіляторів,
         хоча стандарт дозволяє взяти адресу, якщо регістр не використаний.
       - Сучасні компілятори ігнорують цю підказку, якщо вважають за краще інший спосіб оптимізації.
       - Використовуйте register лише як історичну або навчальну довідку; сьогоднішні
         компілятори зазвичай самостійно вирішують, які змінні покласти в регістри.
       - Приклад:
           register int i;
           for (i = 0; i < 10; ++i) {
               // i може бути збережено у регістрі
           }
         Це просто підказка, яка може бути проігнорована.

    3. Ключові відмінності:
       - Область видимості: глобальна vs локальна.
       - Тривалість життя: програма vs виклик функції.
       - Ініціалізація: глобальні отримують 0 за замовчуванням, локальні — ні.
       - Використання: глобальні підходять для спільного стану, але можуть ускладнювати відлагодження.

    4. Приклад використання:
       - Локальна змінна "a" в main() не доступна поза main().
       - Глобальна змінна "counter" доступна з будь-якої функції у файлі.
*/

int counter = 0;          // Глобальна змінна

void increment_counter(void)
{
    counter++;             // Доступ до глобальної змінної з будь-якої функції
}

int sum(int x, int y)
{
    int result = x + y;    // Локальна змінна result
    return result;
}

int main(void)
{
    int a = 5;             // Локальна змінна main
    int b = 10;            // Локальна змінна main

    printf("Global counter before calls = %d\n", counter);

    increment_counter();
    increment_counter();

    printf("Global counter after calls = %d\n", counter);

    int total = sum(a, b);
    printf("Sum %d + %d = %d\n", a, b, total);

    {
        int inner = 42;     // Локальна змінна блоку
        printf("Inner block variable inner = %d\n", inner);
    }

    // printf("%d\n", inner); // Помилка: inner не видно поза блоком

    return 0;
}
