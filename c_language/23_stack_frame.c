#include <stdio.h>

/*
═══════════════════════════════════════════════════════════════════════════════
СТЕКОВИЙ ФРЕЙМ (Stack Frame)
═══════════════════════════════════════════════════════════════════════════════

ЩО ЦЕ?
При запуску програми автоматично виділяється память під стек виклику функцій 
(Стековий фрейм). Стек працює за принципом LIFO (Last In First Out) - 
останній записаний елемент першим видаляється.

ПОСЛІДОВНІСТЬ ЗАВАНТАЖЕННЯ:
1. Завантажуються дані та програмний код в пам'ять
2. Виділяється память під стековий фрейм
3. Першою в стек попадає функція main() (точка входу програми)
4. При кожному виклику функції в стек потрапляють локальні змінні, параметри та адреса повернення
5. Коли функція завершується, вся інформація видаляється зі стеку

ОБМЕЖЕННЯ СТЕКУ:
- Стек має ОБМЕЖЕНУ память (декілька мегабайт, залежить від ОС)
- Розмір стеку залишається ПОСТІЙНИМ під час виконання програми
- При переповненні виникає помилка Stack Overflow

ПРИКЛАДИ:

БУДЕ ПОМИЛКА Stack Overflow:
  double big_array[1000000];  // в функції main - занадто великий масив на стеку
  
  int recursive_func(int n) {
    int array[1000];
    if (n > 0) {
      return recursive_func(n - 1);  // безкінечна рекурсія переповнить стек
    }
  }

НЕ БУДЕ ПОМИЛКИ:
  double big_array[1000000];  // глобальна змінна - зберігається в HEAP/DATA сегменті
  
ВИСНОВОК:
- Локальні змінні функцій → СТЕК (обмежено)
- Глобальні змінні → DATA/BSS сегмент (не обмежено стеком)
- Великі дані → HEAP (динамічна память через malloc/calloc)
═══════════════════════════════════════════════════════════════════════════════
*/

int main(void){
    // Демонстрація неініціалізованої локальної змінної
    int var;
    
    // ВАЖЛИВО: var містить випадкове значення (garbage value) що було в пам'яті до цього (залишки попередніх даних на стеку)
    printf("var = %d\n", var);  // Приклад виводу: 32758, 1044, -5 тощо
    printf("Адреса var: %p\n", (void*)&var);  // Адреса змінної на стеку
    
    return 0;
}