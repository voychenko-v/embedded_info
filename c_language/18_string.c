#include <stdio.h>
#include <string.h>

/*
В C немає окремого рядкового типу даних. Рядок - це масив елементів char,
який закінчується нульовим символом '\0'.

'\0' потрібен функціям для роботи з рядками: strlen, printf("%s"), strcpy тощо.
Без '\0' масив char не є коректним C-рядком.

Рядковий літерал "Hello" має статичний час життя і змінювати його не можна:
const char *p = "Hello";  // правильно для читання
// p[0] = 'h';            // помилка/невизначена поведінка

А масив, створений з літерала, можна змінювати:
char s[] = "Hello";       // копія символів у масиві: H e l l o \0
s[0] = 'h';               // можна
*/

int main(void)
{   
    char s[] = "String";  // Розібє на елементи та додасть '\0'
    char buffer[128] = "Hello";  // Заповнить 5 символів, додасть '\0', решта елементів будуть 0
    char s_2[] = "Hel" "lo"
                    ", world";  // Компілятор збере "Hello, world"
    char s_4[] = "Hello, \
world";  // Компілятор збере "Hello, world"

    // sizeof рахує розмір масиву разом з '\0'
    size_t s_size = sizeof(s);  // 7 байт: S t r i n g \0

    // strlen рахує кількість символів до '\0'
    size_t s_len = strlen(s);   // 6

    // Звернення до символів рядка
    char first = s[0];          // 'S'
    char last = s[s_len - 1];   // 'g'
    s[0] = 's';                 // масив s можна змінювати

    // Екранування і спецсимволи:
    // \" - лапки всередині рядка
    // \\ - зворотний слеш
    // \n - перехід на новий рядок
    // \t - табуляція

    printf("sizeof(s) = %zu, strlen(s) = %zu\n", s_size, s_len);
    printf("first = %c, last = %c\n", first, last);

    // Вивід стрічки
    printf("s = %s\n", s);  // Послідовно перебирає всі елементи масиву доки не дойде до символу закінчення рядка, замість %s будуть підставлені всі символи
    puts(s);  // Дана функція передає все що їй дають і переводит курсор на нову стрічку

    // Читання рядка з вхідного потоку
    char bf[10];
    /*
    scanf("%s", bf);  Другий аргумент масив куди будемо зберігати інформацію з вхідного потоку
    scanf - буде читати до пробільного символу(\n,\t), "Hello world" - запише як "Hello\0" закінчить читання
    scanf("%9s", bf); Обммежуємо читання до 9 елементів
    */

    // Безпечне читання рядків
    fgets(bf, sizeof(bf), stdin);  // fgets(буфер куди записуємо, розмір даних - 1(останій символ автоматично \0), потік) - додає символ переводу стрічки

    char bf_1[10];
    int max_len = sizeof(bf_1), i = 0;
    char *ptr = bf_1, ch;

    // getchar - читає по одному символу
    while((ch = getchar()) != '\n' && ch != EOF && i < max_len - 1)  // Читаємо доки не буде перевод рядка, кінець файлу, максимальна довжина
        ptr[i++] = ch;
    ptr[i] = '\0';

    return 0;
}
