#include <stdio.h>
#include <string.h>

/*
В C немає окремого рядкового типу даних. Рядок - це масив елементів char,
який закінчується нульовим символом '\0'.

'\0' потрібен функціям для роботи з рядками: strlen, printf("%s"), strcpy тощо.
Без '\0' масив char не є коректним C-рядком.

Рядковий літерал "Hello" має статичний час життя і змінювати його не можна:
const char *p = "Hello";  // правильно для читання
// p[0] = 'h';            // помилка/невизначена поведінка

А масив, створений з літерала, можна змінювати:
char s[] = "Hello";       // копія символів у масиві: H e l l o \0
s[0] = 'h';               // можна
*/

int main(void)
{   
    char s[] = "String";  // Розібє на елементи та додасть '\0'
    char buffer[128] = "Hello";  // Заповнить 5 символів, додасть '\0', решта елементів будуть 0
    char s_2[] = "Hel" "lo"
                    ", world";  // Компілятор збере "Hello, world"
    char s_4[] = "Hello, \
world";  // Компілятор збере "Hello, world"

    // sizeof рахує розмір масиву разом з '\0'
    size_t s_size = sizeof(s);  // 7 байт: S t r i n g \0

    // strlen рахує кількість символів до '\0'
    size_t s_len = strlen(s);   // 6

    // Звернення до символів рядка
    char first = s[0];          // 'S'
    char last = s[s_len - 1];   // 'g'
    s[0] = 's';                 // масив s можна змінювати

    // Копіювання рядків. Важливо, щоб у буфері вистачало місця для '\0'
    char copy[32];
    strcpy(copy, s);            // copy = "string"

    // Об'єднання рядків. У copy має вистачити місця для всього результату
    strcat(copy, " literal");   // copy = "string literal"

    // Порівняння рядків: не можна порівнювати через ==, бо це порівняє адреси
    int cmp = strcmp(s, "string");  // 0, якщо рядки однакові

    // Екранування і спецсимволи:
    // \" - лапки всередині рядка
    // \\ - зворотний слеш
    // \n - перехід на новий рядок
    // \t - табуляція

    printf("s = %s\n", s);
    printf("sizeof(s) = %zu, strlen(s) = %zu\n", s_size, s_len);
    printf("first = %c, last = %c\n", first, last);
    printf("copy = %s\n", copy);
    printf("cmp = %d\n", cmp);

    return 0;
}
