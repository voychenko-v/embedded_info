#include <stdio.h>
/*
Масиви

Масив - це набір елементів одного типу, які лежать у пам'яті підряд.
Кожен елемент має свій індекс.

Індекс першого елемента завжди 0.
Індекс останнього елемента: кількість_елементів - 1.

Загальний запис:
<тип елементів> <ім'я масиву>[<кількість елементів>];

Приклад:
double f[30];

Якщо double займає 8 байтів, то весь масив займає:
30 * sizeof(double), тобто зазвичай 30 * 8 = 240 байтів.

У C масив - це неперервна область пам'яті фіксованого розміру.
Сам масив не зберігає інформацію про свою довжину, тому програміст
сам відповідає за те, щоб не виходити за межі індексів.

До стандарту C99 розмір локального масиву можна було задавати тільки
константним виразом. У C99 з'явилися VLA - масиви змінної довжини,
але їх підтримують не всі компілятори та стандарти, тому для переносимого
коду краще використовувати константи або динамічну пам'ять.

Операція sizeof для вказівника на масив повертає число байт зайнятих масивом в памяті.
Адреса вказівника на масив формується в момент його ініціалізації і знаходиться в памяті,
та залишається незмінною на протязі роботи программи.
*/

#define SIZE_ARR 10  // Іменована константа для розміру масиву

int main(void)
{
    // Варіанти створення масиву
    double f[30];              // 30 елементів типу double
    char buffer[SIZE_ARR];     // 10 елементів типу char
    short ar[8 * 2];           // 16 елементів типу short
    char bytes[sizeof(double)]; // Кількість char дорівнює розміру double у байтах

    /*
    Небажані або неправильні варіанти створення масиву:

    int n = 5;

    int array[n];
    Дозволено у C99 як VLA, але це не найкращий варіант для переносимого коду.
    Наприклад, у C11 підтримка VLA стала необов'язковою, а в C++ такого немає.

    int array[22.33];
    Розмір масиву має бути цілим числом.

    int array[0];
    Масив із нулем елементів не є стандартним C.
    */

    int marks[SIZE_ARR] = {0}; // Усі елементи явно ініціалізовані нулями

    marks[2] = 5;       // Записуємо у третій елемент масиву, бо індекси починаються з 0
    int el = marks[2];  // У змінну el записуємо значення третього елемента

    marks[3] = 2 * 4;   // Спочатку виконається множення, потім результат запишеться в marks[3]

    /*
    Межі масиву marks[SIZE_ARR]:
    перший елемент: marks[0]
    останній елемент: marks[SIZE_ARR - 1], тобто marks[9]

    marks[10] = 3;

    Так писати не можна. Це вихід за межі масиву.
    Програма може навіть "працювати", але запис піде в чужу область пам'яті.
    У C це undefined behavior - результат непередбачуваний.
    */

    printf("marks[0] = %d\n", marks[0]);
    printf("marks[2] = %d\n", el);
    printf("marks[3] = %d\n", marks[3]);

    /*
    Якщо створити локальний масив без ініціалізації:

    int values[SIZE_ARR];

    то його елементи мають невизначені значення.
    Читати values[0] до запису значення не можна. 
    Вивід буде типу -1470511912, так як память виділилась і там знаходились мусорні дані.
    */
    
    // Визначаємо довжину масиву
    size_t bytes_marks = sizeof(marks);  // size_t по факту є числом типу long long
    printf("Len arr marks: %zu\n", bytes_marks);  // 40 байтів
    size_t zize_marks = sizeof(marks) / sizeof(marks[0]);  // Кількість елементів 10

    // Ініціалізація масиву значеннями
    int values[5] = {4, 5, 1, 55, 654};  // = тут це операція ініціалізації масиву.
    int values_2[6] = {4}; // Вказали тільки перший елемент масиву, всі інші автоматично будуть 0
    int values_3[4] = {}; // Всі елементи будуть 0, але краще вказати 0 - візуально зрозуміліше
    // Якщо вказати більше елементів ніж в масиві буде помилка при компіляції
    int undef_value[] = {44, 532, 234};  // Довжина масиву визначається за кількістю елементів
    int digits[10] = {-1, [2] = 5, 33, [9] = 3};  // Явно ініціалізуємо елементи в певні індекси, зявилось в С99
    // Ініціалізіція великих масивів білше 1000 елементів впливає на швидкість роботи особливо якщо вона всередині функції мейн
    // Часто масив ініціалізують поза межами функції. Тоді ініціалізація масиву буде тільки при завантаженні програми в память

    // Вказівники на масиви. Імя масиву є вказівником на масив і вміщує адресу на перший елемент
    short s_arr[] = {3, 4, 7, 2, 5, 6};
    short a_1 = *s_arr;  // 3
    short a_4 = *(s_arr + 3);  // Зміщуємось на 3 елементи і отримуємо значення 4 елементу

    short *p_arr;
    p_arr = s_arr;  // Вказівнику присвоюємо адресу масиву
    short x = *p_arr;  // Записуємо значення першого елементу в змінну х

    size_t len_1 = sizeof(s_arr); // 12 кількість байт скільки займає масив
    size_t len_2 = sizeof(p_arr); // 8 кількість байт скільки займає вказівник

    return 0;


}
