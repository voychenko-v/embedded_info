#include <stdio.h>
/*
========== while
Якщо умова правдива, виконується оператор або блок операторів.

while (умова)
    оператор;

while (умова) {
    оператори;
}

========== for
Зручно використовувати, коли відома кількість повторень.

for (ініціалізація; умова; зміна значення) {
    оператори;
}

========== do-while
Спочатку виконує тіло циклу, потім перевіряє умову.
Тіло do-while виконається мінімум 1 раз.

do {
    оператори;
} while (умова);

Для циклів доступні оператори:
break    - достроковий вихід з циклу. Якщо цикли вкладені, break виходить
           тільки з того циклу, де він написаний.
continue - пропуск поточної ітерації та перехід до наступної.
goto     - перехід до мітки в межах поточної функції.

goto для початківців краще не використовувати без потреби, бо він може
ускладнювати читання програми. Іноді його використовують для виходу
одразу з кількох вкладених циклів.

*/


int main(void)
{
    int n = 5;
    int s = 0;

    while (n > 0) {
        // Можна написати n-- > 0: спочатку порівняння, потім декремент.
        // Якщо написати --n > 0, то спочатку декремент, потім порівняння.
        s += n * 2;
        printf("s = %d\n", s);
        n--;
    }

    int i = 0;
    int m = 5;

    while (++i <= m && i <= 10) {
        int loc_var = 2;  // Змінна локальна і не доступна поза межами циклу.
        s += m * loc_var;
        printf("s_2 = %d\n", s);
    }

    int x, y;
    y = 6;

    for (x = 0; y > 0; --y) {
        // Можна ініціалізувати змінні прямо в циклі:
        // for (int x = 0, y = 4; y > 0; --y)
        // Але тоді вони будуть локальні для циклу.
        x += y * y;
        printf("x = %d\n", x);
        // Зміну значення можна винести в тіло циклу, але так код менш компактний.
    }
    
    /*
    n = 5;

    for (x = 1, y = 1; x <= n; y = y * y, ++x)
        ; // Порожнє тіло циклу: вся робота описана в заголовку for.
    */


    int pass_code = 12;
    int enter_code = 12;

    do {
        printf("Please enter the secret code\n");
    } while (enter_code != pass_code);

    printf("Access is allowed\n");

    
    // break
    int b = 4;
    while (1) {
        // На кожній ітерації b зменшується на 1.
        // Коли b стане менше 0, спрацює break і цикл завершиться.
        if (b < 0) {
            printf("Break cycle finished\n");
            break;  // Виходимо з циклу.
        }
        b--;
    }

    // continue
    int c = 10;
    while (c-- > 0) {
        if (c % 2 == 0)
            continue;  // Переходимо на початок циклу і пропускаємо код нижче.
        printf("Value is odd: %d\n", c);
    }

    // goto
    for (int g = 1; g <= 10; g++) {
        if (g == 5) {
            goto finish;
        }
        printf("g = %d\n", g);
    }

    finish:
        printf("Cycle finished with goto\n");


    return 0;
}
