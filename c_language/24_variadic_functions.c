#include <stdio.h>
#include <stdarg.h>

/*
═══════════════════════════════════════════════════════════════════════════════
ВАРІАДИЧНІ ФУНКЦІЇ (Variadic Functions) - функції з довільним числом аргументів
═══════════════════════════════════════════════════════════════════════════════
Потрібно підключити #include <stdarg.h>

ПОСЛІДОВНІСТЬ ВИКОРИСТАННЯ:
1. Визначення функції з принаймні одним фіксованим параметром, після якого йдуть варіадичні аргументи (позначаються трьома крапками '...').
2. Перший фіксований параметр або інша інформація повинні дозволяти визначити, скільки аргументів передано:
   - явний лічильник аргументів, як у цьому прикладі
   - або маркер-завершення (sentinel), наприклад 0 або NULL
3. Використання макросів з бібліотеки <stdarg.h> для обробки варіадичних аргументів:
   - va_list: тип для зберігання інформації про поточну позицію в списку аргументів
   - va_start: ініціалізує va_list, вказуючи на аргумент перед '...'
   - va_arg: отримує наступний аргумент заданого типу
   - va_end: завершує роботу з va_list
4. Увага: при використанні va_arg потрібно точно знати тип кожного переданого аргументу.
   Неправильний тип може призвести до некоректних результатів або аварійного завершення.
*/

int sum(int count, ...)  // Три крапки означають, що може бути передано довільне число аргументів
{
    int s = 0;
    va_list arg;  // Тип для обробки варіадичних аргументів з <stdarg.h>
    va_start(arg, count);  // Ініціалізуємо arg, передаючи останній фіксований параметр

    for (int i = 0; i < count; ++i) {
        s += va_arg(arg, int);  // Отримуємо наступний аргумент типу int
    }

    va_end(arg);  // Завершуємо роботу з va_list
    return s;
}


int main(void)
{
    int res = sum(4, 34, 5, 2, 6);
    printf("res = %d\n", res);

    return 0;
}